// ─── Utility Helpers ─────────────────────────────────────────────
export function getSchemesByPillar(pillarId: PillarId): SchemeModule[] {
  return SCHEME_MODULES.filter((m) => m.pillar === pillarId);
}

export function getSchemeBySlug(slug: string): SchemeModule | undefined {
  return SCHEME_MODULES.find((m) => m.slug === slug);
}

export function getPillar(pillarId: PillarId): Pillar | undefined {
  return PILLARS.find((p) => p.id === pillarId);
}

export function searchSchemes(query: string): SchemeModule[] {
  const q = query.toLowerCase().trim();
  if (!q) return SCHEME_MODULES;
  return SCHEME_MODULES.filter(
    (m) =>
      m.title.toLowerCase().includes(q) ||
      m.titleHi.includes(q) ||
      m.description.toLowerCase().includes(q) ||
      m.pillar.includes(q)
  );
}
